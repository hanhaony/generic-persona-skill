"""中文**字形归一**（繁体 → 简体），只用于"能不能对上"这类判定。

# 为什么要有这个模块

R4.1 实测：相关性判据是简体「福尔摩斯」，页面写的是繁体「福爾摩斯的懸疑世界」
（801 字正文，明确讲福尔摩斯与华生），字面不匹配 ⇒ 被判"与目标无关" ⇒ 拒收。
**本轮最相关的一条，因为字形差异被误杀**（D-7）。

这不是"过滤器太严"，是"判定口径少做了一步"：同一个词有不止一种写法，
而判定的目的是"这是不是同一个词"，不是"这两个字符串是不是逐字相等"。

# 为什么不装 opencc / zhconv

`pyproject.toml` 写着**运行时零第三方依赖**（D-004 / D-068），新增任何依赖
都必须先在 `DECISIONS.md` 记理由。为"词表匹配"引入一个转换库，代价（依赖 +
体积 + 供应链面）远大于收益。所以这里自带一张**常用字表**，纯标准库实现。

# 归一方向：**单向折到简体**，两侧都折

`fold_variants()` 把繁体字折成对应的简体字，简体字原样保留。判定前
**词表和待判文本都折一遍**，于是两个方向都能对上：

- 简体词表「福尔摩斯」 vs 繁体页面「福爾摩斯」 → 都折成「福尔摩斯」 ✔
- 繁体词表「福爾摩斯」 vs 简体页面「福尔摩斯」 → 都折成「福尔摩斯」 ✔

只折一侧是不行的：那只能覆盖"词表是简体"这一种情况。

# ⚠️ 字表的边界（必须知道）

这是**常用字表，不是完整字表**。未收录的繁体字**原样参与匹配**（不会被删掉、
也不会被替换错），后果只是那个词可能仍然对不上——和今天的行为一致，不会更差。
发现漏字就往 `VARIANT_MAP` 里补一行，**并补一条测试**固定它。

另外两点如实说明：

1. **一简对多繁**（如 发/發/髮、台/臺/檯/颱）只折到简体那一侧；反方向有歧义，
   本模块**不做**，所以不会把不同的字折混。
2. 这是**字形归一，不是语义归一**。它解决不了"夏洛克" vs "福尔摩斯"这种译名
   差异——那是另一个问题，别指望这张表。
"""

