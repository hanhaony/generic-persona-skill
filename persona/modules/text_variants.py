def fold_variants(text: str) -> str:
    """把文本折到**简体**这一侧（繁体字换成简体，其余原样）。

    两侧（词表与待判文本）都过一遍这个函数，就能双向对上。见模块文档。
    """
    if not text:
        return ""
    return "".join(VARIANT_MAP.get(ch, ch) for ch in text)


def fold_terms(terms: Iterable[str] | None) -> list[str]:
    """词表整批折到简体侧（保序、去重）。"""
    folded: list[str] = []
    for term in terms or []:
        value = fold_variants(str(term or ""))
        if value and value not in folded:
            folded.append(value)
    return folded
